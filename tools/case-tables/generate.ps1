#requires -Version 7

<#
.SYNOPSIS
Writes GodotCaseTables.g.cs, Godot's case tables as C# spans, from the engine's core/string/ucaps.h.

.DESCRIPTION
Parses ucaps.h's caps_table (lower case to upper case) and reverse_caps_table (upper case to lower case), checks each
table's pair count against the LTU_LEN and UTL_LEN defines in the same file and that each table's keys are strictly
ascending (the engine's _find_upper and _find_lower binary-search them), and writes a C# file declaring
GodotCaseTables.UpperFrom, UpperTo, LowerFrom and LowerTo. The file carries ucaps.h's license block and is written with
LF line endings and a final newline; the same ucaps.h always gives the same bytes.

.PARAMETER Ucaps
The path to ucaps.h in a Godot source tree, e.g. <godot source>/core/string/ucaps.h.

.PARAMETER Out
The path of the C# file to write, e.g. src/GodotXaml.Core/Names/GodotCaseTables.g.cs.

.PARAMETER GodotVersion
The Godot version the ucaps.h comes from, named in the generated file's header.

.PARAMETER UnicodeVersion
The Unicode version Godot generated that ucaps.h from (misc/scripts/ucaps_fetch.py), named in the header.

.EXAMPLE
pwsh -NoProfile -File tools/case-tables/generate.ps1 -Ucaps <godot source>/core/string/ucaps.h -Out src/GodotXaml.Core/Names/GodotCaseTables.g.cs
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$Ucaps,

    [Parameter(Mandatory)]
    [string]$Out,

    [string]$GodotVersion = '4.8-beta2',

    [string]$UnicodeVersion = '18.0.0'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$lines = (Get-Content -LiteralPath $Ucaps -Raw) -split '\r?\n'

# The define named $Name in ucaps.h, as an integer.
function Get-Define([string]$Name) {
    foreach ($line in $lines) {
        if ($line -match "^\s*#define\s+$Name\s+(\d+)\s*$") {
            return [int]$Matches[1]
        }
    }
    throw "ucaps.h defines no $Name."
}

# Checks that a table has the define's pair count and strictly ascending keys.
function Test-Table([string]$Table, [string]$Define, [System.Collections.Generic.List[int[]]]$Pairs) {
    $expected = Get-Define $Define
    if ($Pairs.Count -ne $expected) {
        throw "$Table has $($Pairs.Count) pairs; ucaps.h's $Define is $expected."
    }
    for ($i = 1; $i -lt $Pairs.Count; $i++) {
        if ($Pairs[$i][0] -le $Pairs[$i - 1][0]) {
            throw ('{0} is not strictly ascending at index {1}: 0x{2:X4} follows 0x{3:X4}.' -f
                $Table, $i, $Pairs[$i][0], $Pairs[$i - 1][0])
        }
    }
}

# The table's pairs: caps_table's from its first line to the line declaring reverse_caps_table, reverse_caps_table's
# from there on.
$caps = [System.Collections.Generic.List[int[]]]::new()
$reverse = [System.Collections.Generic.List[int[]]]::new()
$current = $null
foreach ($line in $lines) {
    if ($line -match '\breverse_caps_table\s*\[') {
        $current = $reverse
    }
    elseif ($null -eq $current -and $line -match '\bcaps_table\s*\[') {
        $current = $caps
    }

    if ($null -ne $current -and $line -match '\{\s*0x([0-9A-Fa-f]+)\s*,\s*0x([0-9A-Fa-f]+)\s*\}') {
        $current.Add(@([Convert]::ToInt32($Matches[1], 16), [Convert]::ToInt32($Matches[2], 16)))
    }
}

Test-Table 'caps_table' 'LTU_LEN' $caps
Test-Table 'reverse_caps_table' 'UTL_LEN' $reverse

# ucaps.h's license block: its leading /* ... */ lines.
$license = [System.Collections.Generic.List[string]]::new()
foreach ($line in $lines) {
    if (-not $line.StartsWith('/*')) {
        break
    }
    $license.Add($line)
}
if ($license.Count -eq 0) {
    throw 'ucaps.h does not open with its license block.'
}

# Resolved against the PowerShell location, which .NET's own current directory need not match.
$outFull = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Out)
$outRelative = [System.IO.Path]::GetRelativePath($repoRoot, $outFull).Replace('\', '/')

$text = [System.Text.StringBuilder]::new()
# Appends one line, LF-terminated.
function Add-Line([string]$Line = '') {
    [void]$text.Append($Line).Append("`n")
}

# Appends one member: a span of one table column, eight values to a line.
function Add-Span([string]$Name, [string]$Summary, [System.Collections.Generic.List[int[]]]$Pairs, [int]$Column) {
    Add-Line "    /// <summary>$Summary</summary>"
    Add-Line "    internal static ReadOnlySpan<int> $Name =>"
    Add-Line '        ['
    for ($i = 0; $i -lt $Pairs.Count; $i += 8) {
        $end = [Math]::Min($i + 8, $Pairs.Count)
        $values = for ($j = $i; $j -lt $end; $j++) { '0x{0:X4}' -f $Pairs[$j][$Column] }
        Add-Line ('            ' + ($values -join ', ') + ',')
    }
    Add-Line '        ];'
}

Add-Line '// <auto-generated/>'
Add-Line "// Godot $GodotVersion's core/string/ucaps.h, generated there from Unicode $UnicodeVersion, as C# spans. Written by:"
Add-Line '//     pwsh -NoProfile -File tools/case-tables/generate.ps1 -Ucaps <godot source>/core/string/ucaps.h'
Add-Line "//         -Out $outRelative"
Add-Line '// Do not edit; run the command again on a new ucaps.h. ucaps.h carries this license:'
Add-Line '//'
foreach ($line in $license) {
    Add-Line "// $line"
}
Add-Line
Add-Line 'namespace GodotXaml.Core.Names;'
Add-Line
Add-Line '/// <summary>Godot''s simple case mappings, the tables ucaps.h''s _find_upper and _find_lower search.</summary>'
Add-Line 'internal static class GodotCaseTables'
Add-Line '{'
Add-Span 'UpperFrom' 'caps_table''s first column: the code points that have an upper case, ascending.' $caps 0
Add-Line
Add-Span 'UpperTo' 'caps_table''s second column: the upper case of the code point at the same index of UpperFrom.' $caps 1
Add-Line
Add-Span 'LowerFrom' 'reverse_caps_table''s first column: the code points that have a lower case, ascending.' $reverse 0
Add-Line
Add-Span 'LowerTo' 'reverse_caps_table''s second column: the lower case of the code point at the same index of LowerFrom.' $reverse 1
Add-Line '}'

[System.IO.File]::WriteAllText($outFull, $text.ToString(), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $outRelative`: caps_table $($caps.Count) pairs, reverse_caps_table $($reverse.Count) pairs."
